"""Alembic migration round trips, drift check and history shape on real PostGIS.

Alembic runs in-process through ``alembic.command`` with the container URL passed as
``-x database_url=...``, exactly as a developer would pass it on the command line.
The tests are plain ``def`` functions on purpose: ``migrations/env.py`` drives its own
event loop with ``asyncio.run``, which cannot start inside a running pytest-asyncio
loop.

Every test leaves the session database empty (no application tables, no
``alembic_version``) because the platform integration tests create the outbox table
themselves and would collide with a migrated schema.
"""

import asyncio
import io
from argparse import Namespace
from collections.abc import Iterator
from pathlib import Path
from typing import Final

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Connection, inspect, text
from sqlalchemy.ext.asyncio import create_async_engine

pytestmark = pytest.mark.integration

REPOSITORY_ROOT: Final = Path(__file__).resolve().parents[3]
ALEMBIC_INI: Final = REPOSITORY_ROOT / "alembic.ini"

VERSION_TABLE: Final = "alembic_version"
# Tables the PostGIS image creates in the public schema; they are not ours.
POSTGIS_TABLES: Final = frozenset({"spatial_ref_sys"})
APPLICATION_TABLES_AT_HEAD: Final = frozenset(
    {
        "outbox_messages",
        "places",
        "place_names",
        "hazard_types",
        "impact_metrics",
        "users",
        "organizations",
        "memberships",
        "idempotency_keys",
        "sources",
        "audit_entries",
        "reports",
        "media_assets",
        "events",
        "event_relations",
        "event_report_links",
        "verification_cases",
        "infrastructure_assets",
        "impact_claims",
        "damage_records",
        "datasets",
        "dataset_versions",
        "ingestion_runs",
        "observations",
        "raster_assets",
        "export_jobs",
        "import_jobs",
    }
)
EXTENSIONS: Final = frozenset({"postgis", "pg_trgm", "unaccent"})


def _read_public_tables(connection: Connection) -> set[str]:
    """Return the table names in the public schema."""
    return set(inspect(connection).get_table_names(schema="public"))


async def _fetch_public_tables(database_url: str) -> set[str]:
    """Connect once and list the public tables."""
    engine = create_async_engine(database_url)
    try:
        async with engine.connect() as connection:
            return await connection.run_sync(_read_public_tables)
    finally:
        await engine.dispose()


async def _fetch_extensions(database_url: str) -> set[str]:
    """Connect once and list the installed extensions."""
    engine = create_async_engine(database_url)
    try:
        async with engine.connect() as connection:
            result = await connection.execute(text("SELECT extname FROM pg_extension"))
            return set(result.scalars().all())
    finally:
        await engine.dispose()


async def _execute(database_url: str, statement: str) -> None:
    """Run one fixed DDL statement in its own transaction."""
    engine = create_async_engine(database_url)
    try:
        async with engine.begin() as connection:
            await connection.execute(text(statement))
    finally:
        await engine.dispose()


def _application_tables(database_url: str) -> set[str]:
    """Return every public table that is neither PostGIS's nor Alembic's."""
    tables = asyncio.run(_fetch_public_tables(database_url))
    return tables - POSTGIS_TABLES - {VERSION_TABLE}


def _build_config(
    database_url: str, output_buffer: io.StringIO | None = None
) -> Config:
    """Return an Alembic config for ``alembic.ini`` aimed at ``database_url``."""
    config = Config(
        ALEMBIC_INI,
        cmd_opts=Namespace(x=[f"database_url={database_url}"]),
        output_buffer=output_buffer,
    )
    # env.py would otherwise call fileConfig and replace pytest's log handlers.
    config.attributes["configure_logger"] = False
    return config


@pytest.fixture
def alembic_config(postgis_url: str) -> Iterator[Config]:
    """Yield a config on the empty session database and empty it again afterwards."""
    config = _build_config(postgis_url)

    yield config

    command.downgrade(config, "base")
    # downgrade base only empties the version table; drop it so the database is
    # exactly as empty as the platform tests expect.
    asyncio.run(_execute(postgis_url, f"DROP TABLE IF EXISTS {VERSION_TABLE}"))


def test_migrations_upgrade_head_downgrade_base_leaves_empty_schema(
    alembic_config: Config, postgis_url: str
) -> None:
    assert _application_tables(postgis_url) == set()

    command.upgrade(alembic_config, "head")
    tables_at_head = _application_tables(postgis_url)
    extensions_at_head = asyncio.run(_fetch_extensions(postgis_url))
    command.downgrade(alembic_config, "base")
    tables_at_base = _application_tables(postgis_url)

    assert tables_at_head == APPLICATION_TABLES_AT_HEAD
    assert extensions_at_head >= EXTENSIONS
    assert tables_at_base == set()


def test_migrations_upgrade_twice_is_idempotent_after_downgrade(
    alembic_config: Config, postgis_url: str
) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")

    command.upgrade(alembic_config, "head")

    assert _application_tables(postgis_url) == APPLICATION_TABLES_AT_HEAD


def test_alembic_check_reports_no_drift_at_head(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")

    # Raises AutogenerateDiffsDetected if the models and the migrations disagree.
    command.check(alembic_config)


def test_alembic_check_with_column_altered_by_hand_reports_drift(
    alembic_config: Config, postgis_url: str
) -> None:
    command.upgrade(alembic_config, "head")
    # A change downgrade still undoes (it drops the whole table), so the fixture's
    # teardown keeps working.
    asyncio.run(
        _execute(
            postgis_url,
            "ALTER TABLE outbox_messages ALTER COLUMN last_error SET NOT NULL",
        )
    )

    with pytest.raises(AutogenerateDiffsDetected, match="last_error"):
        command.check(alembic_config)


def test_migrations_offline_mode_renders_outbox_sql_without_connecting(
    postgis_url: str,
) -> None:
    output = io.StringIO()
    config = _build_config(postgis_url, output_buffer=output)

    command.upgrade(config, "head", sql=True)

    rendered = output.getvalue()
    assert "CREATE EXTENSION IF NOT EXISTS postgis" in rendered
    assert "CREATE TABLE outbox_messages" in rendered
    assert _application_tables(postgis_url) == set()


def _read_observations_layout(
    connection: Connection,
) -> tuple[list[str], list[object]]:
    """Return the primary key columns and foreign keys of ``observations``."""
    inspector = inspect(connection)
    primary_key = inspector.get_pk_constraint("observations")["constrained_columns"]
    return list(primary_key), list(inspector.get_foreign_keys("observations"))


async def _fetch_observations_layout(
    database_url: str,
) -> tuple[list[str], list[object]]:
    """Connect once and read the ``observations`` key layout."""
    engine = create_async_engine(database_url)
    try:
        async with engine.connect() as connection:
            return await connection.run_sync(_read_observations_layout)
    finally:
        await engine.dispose()


def test_migrations_observations_key_is_time_first_without_foreign_keys(
    alembic_config: Config, postgis_url: str
) -> None:
    command.upgrade(alembic_config, "head")

    primary_key, foreign_keys = asyncio.run(_fetch_observations_layout(postgis_url))

    # TimescaleDB hypertables need the time column in every unique index and cannot
    # be blocked by foreign keys; this is what keeps the table hypertable-ready.
    assert primary_key == [
        "observed_at",
        "dataset_version_id",
        "variable_code",
        "site_ref",
    ]
    assert foreign_keys == []


def test_migration_history_is_linear() -> None:
    script = ScriptDirectory.from_config(Config(ALEMBIC_INI))

    revisions = list(script.walk_revisions())

    assert len(script.get_heads()) == 1
    assert len(script.get_bases()) == 1
    assert all(
        revision.down_revision is None or isinstance(revision.down_revision, str)
        for revision in revisions
    )
    assert all(not revision.branch_labels for revision in revisions)


_EXPORT_ROW: Final = (
    "INSERT INTO export_jobs (id, requested_by, dataset, format, filters, status, "
    "sidecar, requested_at, version) VALUES ('{id}', "
    "'01890000-0000-7000-8000-0000000000aa', '{dataset}', 'csv', '{{}}', "
    "'{status}', {sidecar}, '2026-09-01T00:00:00Z', 1)"
)
_REPORTS_JOB: Final = "01890000-0000-7000-8000-0000000000a1"
_EVENTS_JOB: Final = "01890000-0000-7000-8000-0000000000a2"


async def _fetch_visibility(database_url: str) -> dict[str, tuple[object, ...]]:
    """Return ``id -> (visibility column, sidecar's visibility key)`` per export."""
    engine = create_async_engine(database_url)
    try:
        async with engine.connect() as connection:
            has_column = "visibility" in {
                column["name"]
                for column in await connection.run_sync(
                    lambda sync: inspect(sync).get_columns("export_jobs")
                )
            }
            column = "visibility" if has_column else "NULL"
            result = await connection.execute(
                text(
                    f"SELECT id::text, {column}, sidecar ->> 'visibility', "  # noqa: S608  # reason: the column name is one of two literals above
                    "sidecar ? 'visibility' FROM export_jobs"
                )
            )
            return {row[0]: tuple(row[1:]) for row in result}
    finally:
        await engine.dispose()


def test_migration_0018_labels_reports_exports_and_sidecars_reversibly(
    alembic_config: Config, postgis_url: str
) -> None:
    command.upgrade(alembic_config, "0017")
    reports = _EXPORT_ROW.format(
        id=_REPORTS_JOB,
        dataset="reports",
        status="completed",
        sidecar="""'{"row_count": 1}'""",
    )
    events = _EXPORT_ROW.format(
        id=_EVENTS_JOB, dataset="events", status="queued", sidecar="NULL"
    )
    asyncio.run(_execute(postgis_url, reports))
    asyncio.run(_execute(postgis_url, events))

    command.upgrade(alembic_config, "0018")
    upgraded = asyncio.run(_fetch_visibility(postgis_url))
    command.downgrade(alembic_config, "0017")
    downgraded = asyncio.run(_fetch_visibility(postgis_url))
    asyncio.run(_execute(postgis_url, "DELETE FROM export_jobs"))

    assert upgraded == {
        _REPORTS_JOB: ("moderation", "moderation", True),
        _EVENTS_JOB: ("public", None, None),
    }
    assert downgraded[_REPORTS_JOB] == (None, None, False)
