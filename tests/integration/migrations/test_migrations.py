def test_migration_0026_adds_revision_check_and_queue_indexes_reversibly(
    alembic_config: Config, postgis_url: str
) -> None:
    command.upgrade(alembic_config, "0025")
    asyncio.run(
        _insert(
            postgis_url,
            _Row(number=61, lineage=61),
            _Row(number=62, revision=2, supersedes=61, lineage=61),
        )
    )
    orphan = _Row(number=63, revision=2, lineage=61)

    command.upgrade(alembic_config, "0026")
    indexes = asyncio.run(_fetch_index_names(postgis_url))
    with pytest.raises(IntegrityError, match="first_revision_supersedes_nothing"):
        asyncio.run(_insert(postgis_url, orphan))
    command.downgrade(alembic_config, "0025")
    downgraded_indexes = asyncio.run(_fetch_index_names(postgis_url))
    asyncio.run(_insert(postgis_url, orphan))
    _delete_reports(postgis_url)

    new_indexes = {"ix_reports_triage_gin", "ix_media_assets_completed_created_at_id"}
    assert new_indexes <= indexes
    assert not new_indexes & downgraded_indexes


async def _fetch_index_names(database_url: str) -> set[str]:
    """Return the names of every index in the public schema."""
    engine = create_async_engine(database_url)
    try:
        async with engine.connect() as connection:
            result = await connection.execute(
                text("SELECT indexname FROM pg_indexes WHERE schemaname = 'public'")
            )
            return set(result.scalars().all())
    finally:
        await engine.dispose()
