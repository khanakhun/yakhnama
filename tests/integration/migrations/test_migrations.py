class _Row(BaseModel):
    """One synthetic report row for the lineage migrations' tests.

    Implements: Value Object.

    Attributes:
        number: The last digits of its id.
        revision: Its revision number.
        supersedes: The number of the report it supersedes, if any.
        status: Its status.
        channel: How it arrived.
        lineage: The number of its lineage root, for schemas from 0025 on.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    number: int
    revision: int = 1
    supersedes: int | None = None
    status: str = "submitted"
    channel: str = "account"
    lineage: int | None = None


def _report_id(number: int) -> str:
    return f"01890000-0000-7000-8000-0000000{number:05d}"


async def _insert(database_url: str, *rows: _Row) -> None:
    """Insert synthetic reports in order, in one transaction."""
    engine = create_async_engine(database_url)
    try:
        async with engine.begin() as connection:
            for row in rows:
                parameters: dict[str, object] = {
                    "id": _report_id(row.number),
                    "status": row.status,
                    "revision": row.revision,
                    "supersedes_id": (
                        None if row.supersedes is None else _report_id(row.supersedes)
                    ),
                    "withdrawal_reason": (
                        "Test withdrawal." if row.status == "withdrawn" else None
                    ),
                    "channel": row.channel,
                    "created_at": _ROWS_CREATED + timedelta(seconds=row.number),
                }
                statement = _INSERT_REPORT
                if row.lineage is not None:
                    parameters["lineage_id"] = _report_id(row.lineage)
                    statement = _INSERT_REPORT_WITH_LINEAGE
                await connection.execute(text(statement), parameters)
    finally:
        await engine.dispose()


async def _supersede(database_url: str, *pairs: tuple[int, int]) -> None:
    """Mark each ``(old, new)`` pair's old report superseded by the new one."""
    engine = create_async_engine(database_url)
    try:
        async with engine.begin() as connection:
            for old, new in pairs:
                await connection.execute(
                    text(_SUPERSEDE), {"old": _report_id(old), "new": _report_id(new)}
                )
    finally:
        await engine.dispose()


def _delete_reports(database_url: str) -> None:
    """Delete every report, breaking the revision links first."""
    for statement in (
        "UPDATE reports SET superseded_by_id = NULL",
        "UPDATE reports SET supersedes_id = NULL",
        "DELETE FROM reports",
    ):
        asyncio.run(_execute(database_url, statement))


def test_migration_0025_backfills_long_chains_withdrawn_and_guest_lineages(
    alembic_config: Config, postgis_url: str
) -> None:
    command.upgrade(alembic_config, "0024")
    asyncio.run(
        _insert(
            postgis_url,
            # A chain of four revisions: 1 <- 2 <- 3 <- 4, the first three superseded.
            _Row(number=1),
            _Row(number=2, revision=2, supersedes=1),
            _Row(number=3, revision=3, supersedes=2),
            _Row(number=4, revision=4, supersedes=3),
            # A correction later withdrawn by its reporter.
            _Row(number=11),
            _Row(number=12, revision=2, supersedes=11, status="withdrawn"),
            # A guest report, and a withdrawn first revision.
            _Row(number=21, channel="guest"),
            _Row(number=31, status="withdrawn"),
        )
    )
    asyncio.run(_supersede(postgis_url, (1, 2), (2, 3), (3, 4), (11, 12)))

